  const normalize = (language) => dictionaries[language] ? language : 'zh-CN';

  const t = (language, key) => {
    const lang = normalize(language);
    return dictionaries[lang][key] || dictionaries['zh-CN'][key] || key;
  };

  const setText = (root, selector, value) => {
    root.querySelectorAll(selector).forEach((node) => {
      node.textContent = value;
    });
  };

  const setAttr = (root, selector, attr, value) => {
    root.querySelectorAll(selector).forEach((node) => {
      node.setAttribute(attr, value);
    });
  };

  const applyMap = (root, language, map) => {
    Object.entries(map.text || {}).forEach(([selector, key]) => setText(root, selector, t(language, key)));
    Object.entries(map.htmlLang || {}).forEach(([selector, value]) => {
      root.querySelectorAll(selector).forEach((node) => {
        node.lang = normalize(language);
      });
    });
    Object.entries(map.title || {}).forEach(([selector, key]) => setAttr(root, selector, 'title', t(language, key)));
    Object.entries(map.aria || {}).forEach(([selector, key]) => setAttr(root, selector, 'aria-label', t(language, key)));
    Object.entries(map.placeholder || {}).forEach(([selector, key]) => setAttr(root, selector, 'placeholder', t(language, key)));
  };

  return { dictionaries, normalize, t, applyMap };
